'use strict';

/**
 * Builds the GitHub Pages site in `docs/` from the application's own sources.
 *
 * The site is static — no framework, no bundler — but nothing about it is a
 * copy-paste of the app. Everything visual or behavioural is generated from the
 * one place the app keeps it:
 *
 *   src/renderer/icons.js     -> docs/assets/verity-art.js   (mascot, mark, icons)
 *   src/renderer/chrome.css   -> docs/assets/palette.css     (the palette tokens)
 *   src/main/blocklist.js     -> docs/assets/verity-engine.js (the rule engine)
 *   src/main/search.js        -> docs/assets/verity-engine.js (the omnibox resolver)
 *   src/main/settings.js      -> docs/assets/verity-engine.js (the engine list)
 *
 * The site's "try the rules" panel therefore runs the same code the browser runs,
 * not a re-implementation that will drift from it. This is the same principle as
 * tools/make-icon.js: the window icon is drawn from VERITY_MARK so it cannot
 * disagree with the face in the strip.
 *
 * After generating, it re-loads the emitted files in a sandbox and compares them
 * against the real modules across a probe set, so a broken bundle fails the
 * build instead of shipping a website whose demo lies.
 *
 * Usage: node tools/build-site.js
 */

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const Module = require('module');

const ROOT = path.join(__dirname, '..');

/*
 * src/main/settings.js imports Electron, which a website cannot have. The only
 * values the site needs from it are SEARCH_ENGINES and DEFAULTS — frozen
 * literals that never touch Electron, which appears solely inside the Settings
 * class constructor. So the build intercepts that one require, which also lets
 * this run on a CI runner with no node_modules at all. Nothing is swallowed:
 * the module still loads for real, and the values it exports are the ones that
 * get embedded in the page.
 */
let electronStubbed = false;
const loadModule = Module._load;
Module._load = function interceptElectron(request, ...rest) {
  if (request === 'electron') {
    electronStubbed = true;
    return { app: { getPath: () => path.join(ROOT, '.electron-is-not-available-here') } };
  }
  return loadModule.call(this, request, ...rest);
};
const DOCS = path.join(ROOT, 'docs');
const ASSETS = path.join(DOCS, 'assets');

const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const pkg = JSON.parse(read('package.json'));

const problems = [];
const wrote = [];
const note = (line) => console.log(`  ${line}`);

function write(rel, contents) {
  const full = path.join(DOCS, rel);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  const previous = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
  fs.writeFileSync(full, contents);
  wrote.push({ rel, changed: previous !== contents, bytes: Buffer.byteLength(contents) });
}

const header = (what, sources) =>
  `/* ${what}\n *\n * GENERATED by tools/build-site.js — do not edit.\n * Source of truth: ${sources.join(', ')}\n */\n`;

/* --------------------------------------------------------------- CSS tokens
 * The palette lives in chrome.css as custom properties. Rather than retyping
 * the hex codes into the site's stylesheet (and having them drift), lift the
 * declarations straight out of the app's own blocks.
 */

function cssBlock(css, selector) {
  const at = css.indexOf(selector);
  if (at === -1) throw new Error(`selector not found in chrome.css: ${selector}`);
  const open = css.indexOf('{', at);
  let depth = 0;
  for (let i = open; i < css.length; i += 1) {
    if (css[i] === '{') depth += 1;
    else if (css[i] === '}') {
      depth -= 1;
      if (depth === 0) return css.slice(open + 1, i);
    }
  }
  throw new Error(`unbalanced block for ${selector}`);
}

function declarations(block) {
  const out = new Map();
  for (const line of block.split(/\r?\n/)) {
    const match = /^\s*(--[a-z0-9-]+)\s*:\s*([^;]+);/i.exec(line);
    if (match) out.set(match[1], match[2].trim());
  }
  return out;
}

function palette() {
  const css = read('src/renderer/chrome.css');
  const base = declarations(cssBlock(css, ':root {'));
  const dark = new Map([...base, ...declarations(cssBlock(css, ":root,\n[data-theme='dark'] {"))]);
  const light = declarations(cssBlock(css, "[data-theme='light'] {"));
  for (const key of base.keys()) if (!light.has(key)) light.set(key, base.get(key));
  if (!dark.get('--accent') || !light.get('--accent')) problems.push('palette: --accent missing');
  const block = (map, indent = '  ') => [...map].map(([k, v]) => `${indent}${k}: ${v};`).join('\n');
  return header('Verity\'s palette, as the app declares it.', ['src/renderer/chrome.css']) +
    `:root {\n${block(dark)}\n  color-scheme: dark;\n}\n\n` +
    `[data-theme='light'] {\n${block(light)}\n  color-scheme: light;\n}\n`;
}

/* --------------------------------------------------------------------- Art
 * icons.js is a plain script that assigns to globalThis, so it can be dropped
 * into the page verbatim — the site draws the mascot with the app's own code.
 */
function art() {
  const source = read('src/renderer/icons.js');
  const sandbox = {};
  sandbox.globalThis = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(source, sandbox, { filename: 'icons.js' });
  for (const name of ['verityMascot', 'verityMark', 'verityFavicon', 'VERITY_ICONS', 'VERITY_MARK']) {
    if (!sandbox[name]) problems.push(`art: icons.js did not define ${name}`);
  }
  const glue = `
/* The site's art API. icons.js above assigns to globalThis, exactly as it does
   inside the app, so everything below is the app's own drawing code. */
(function () {
  window.VERITY_ART = {
    mascot: globalThis.verityMascot,
    mark: globalThis.verityMark,
    favicon: globalThis.verityFavicon,
    icons: globalThis.VERITY_ICONS,
    MARK: globalThis.VERITY_MARK,
  };
})();
`;
  write('assets/verity-art.js', header('Verity\'s mascot, mark and icons.', ['src/renderer/icons.js']) + source + glue);
  return { sandbox };
}

/* ------------------------------------------------------------------ Engine
 * A four-line CommonJS registry, because blocklist.js and search.js are
 * main-process modules: the site runs them unmodified, and only the one
 * dependency they need (the engine table) is supplied from the real settings
 * module, serialised at build time.
 */
function engine() {
  let settings;
  try {
    settings = require('../src/main/settings.js');
  } catch (error) {
    problems.push(`engine: could not load src/main/settings.js (${error.message})`);
    throw error;
  }
  const engines = settings.SEARCH_ENGINES;
  if (!engines || !engines.duckduckgo) problems.push('engine: SEARCH_ENGINES looks wrong');

  const modules = {
    './blocklist': read('src/main/blocklist.js'),
    './search': read('src/main/search.js'),
  };

  const stubs = {
    './settings': `exports.SEARCH_ENGINES = ${JSON.stringify(engines, null, 2)};\n`,
  };

  const registry = Object.entries({ ...modules, ...stubs })
    .map(([name, source]) =>
      `  ${JSON.stringify(name)}: function (module, exports, require) {\n${source.replace(/^(?!\s*$)/gm, '    ')}\n  },`)
    .join('\n');

  const bundle = `${header('The parts of Verity\'s privacy engine the site can run in a page.', [
    'src/main/blocklist.js',
    'src/main/search.js',
    'src/main/settings.js',
  ])}
(function () {
  var registry = {
${registry}
  };
  var cache = {};

  function load(name) {
    if (cache[name]) return cache[name].exports;
    var factory = registry[name];
    if (!factory) throw new Error('no module ' + name);
    var module = { exports: {} };
    cache[name] = module;
    factory(module, module.exports, load);
    return module.exports;
  }

  var blocklist = load('./blocklist');
  var search = load('./search');

  window.VERITY_ENGINE = {
    Blocklist: blocklist.Blocklist,
    stripTrackingParams: blocklist.stripTrackingParams,
    TRACKING_PARAMS: blocklist.TRACKING_PARAMS,
    RAW_LIST: blocklist.RAW_LIST,
    parseList: blocklist.parseList,
    normalisePattern: blocklist.normalisePattern,
    resolveInput: search.resolveInput,
    looksLikeUrl: search.looksLikeUrl,
    searchUrl: search.searchUrl,
  };
})();
`;
  write('assets/verity-engine.js', bundle);
  return { blocklist: require('../src/main/blocklist.js'), search: require('../src/main/search.js'), settings };
}

/* -------------------------------------------------------------------- Data
 * Numbers on the site are measured from the sources, not typed by hand.
 */
function data(real, checks) {
  const list = new real.blocklist.Blocklist();
  const payload = {
    product: { name: pkg.productName || pkg.name, version: pkg.version, description: pkg.description },
    // How many probe cases the build compared against the app's own modules.
    probes: checks ? checks.probes : 0,
    filterList: list.describe(),
    trackingParams: real.blocklist.TRACKING_PARAMS.map((re) => String(re).replace(/^\/\^?|\$?\/[a-z]*$/gi, '')),
    searchEngines: Object.entries(real.settings.SEARCH_ENGINES).map(([key, value]) => ({ key, label: value.label })),
    defaults: Object.entries(real.settings.DEFAULTS || {})
      .filter(([, value]) => value === true)
      .map(([key]) => key),
  };
  write('assets/verity-data.js', header('Measurements taken from the app at build time.', [
    'src/main/blocklist.js',
    'src/main/settings.js',
    'package.json',
  ]) + `window.VERITY_DATA = ${JSON.stringify(payload, null, 2)};\n`);
  return payload;
}

/* ------------------------------------------------------------------ Shots
 * artifacts/ is gitignored, so the captures the site shows are copied in. When
 * it is absent (a fresh clone) the committed copies are left alone.
 */
function shots() {
  const wanted = [
    ['03-page-newtab.png', 'the-new-tab-page.png'],
    ['02-chrome-strip.png', 'the-strip.png'],
    ['07-chrome-strip-multitab.png', 'the-strip-multitab.png'],
  ];
  const from = path.join(ROOT, 'artifacts');
  if (!fs.existsSync(from)) {
    note('artifacts/ is absent — keeping the committed captures');
    return 0;
  }
  let copied = 0;
  for (const [source, target] of wanted) {
    const full = path.join(from, source);
    if (!fs.existsSync(full)) {
      note(`no capture for ${source} — skipped`);
      continue;
    }
    const bytes = fs.readFileSync(full);
    const out = path.join(ASSETS, 'shots', target);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    const changed = !fs.existsSync(out) || !fs.readFileSync(out).equals(bytes);
    fs.writeFileSync(out, bytes);
    wrote.push({ rel: `assets/shots/${target}`, changed, bytes: bytes.length });
    copied += 1;
  }
  return copied;
}

/* --------------------------------------------------------------- Verify it
 * Load the emitted bundle in a sandbox and compare it, case by case, with the
 * modules it was built from. Anything that differs fails the build.
 */
const HOSTS = [
  'ad.doubleclick.net', 'doubleclick.net', 'notdoubleclick.net', 'doubleclick.net.evil.com',
  'a.b.doubleclick.net', 'www.google-analytics.com', 'google-analytics.com', 'mygoogle-analytics.com',
  'coinhive.com', 'example.com', 'sub.example.com', 'localhost', '127.0.0.1', '', null,
  'pixel.facebook.com', 'facebook.com', 'cdn.jsdelivr.net', 't.co', 'stats.g.doubleclick.net',
];

const URLS = [
  'https://shop.example.com/item?utm_source=news&utm_medium=email&id=42',
  'https://example.com/?fbclid=abc123&gclid=xyz&keep=1',
  'https://example.com/?a=1&b=2',
  'https://example.com/',
  'https://example.com/?UTM_CAMPAIGN=Spring',
  'https://example.com/?ref_src=twsrc&s_cid=1&mc_eid=2',
  'http://tracked.example/?trk_id=9&campaignid=7#frag',
  'not a url',
  'mailto:someone@example.com',
];

const INPUTS = ['', 'weather', 'example.com', 'kagi.com/path?q=1', 'localhost:3000', '127.0.0.1:8080', 'https://x.dev/s', 'verity://newtab', 'two words', 'what is 2+2', 'a.b.co.uk', 'file.txt?', 'foo.bar'];

function verify(real) {
  const files = ['assets/verity-art.js', 'assets/verity-engine.js'];
  const sandbox = { console, URL, encodeURIComponent, decodeURIComponent, setTimeout, clearTimeout };
  sandbox.window = sandbox;
  sandbox.globalThis = sandbox;
  vm.createContext(sandbox);

  for (const rel of files) {
    const source = fs.readFileSync(path.join(DOCS, rel), 'utf8');
    try {
      vm.runInContext(source, sandbox, { filename: rel });
    } catch (error) {
      problems.push(`${rel} did not load: ${error.message}`);
      return;
    }
  }

  const art = sandbox.VERITY_ART;
  const eng = sandbox.VERITY_ENGINE;
  if (!art || !eng) {
    problems.push('generated files loaded but did not publish VERITY_ART/VERITY_ENGINE');
    return;
  }

  // The art is the app's art, byte for byte, at the sizes the site uses.
  const artSandbox = {};
  artSandbox.globalThis = artSandbox;
  vm.createContext(artSandbox);
  vm.runInContext(read('src/renderer/icons.js'), artSandbox, { filename: 'icons.js' });
  for (const size of [18, 26, 64, 96]) {
    if (art.mark({ size }) !== artSandbox.verityMark({ size })) problems.push(`mark(${size}) differs from the app's`);
    if (art.mascot({ size, mood: 'happy' }) !== artSandbox.verityMascot({ size, mood: 'happy' })) {
      problems.push(`mascot(${size}) differs from the app's`);
    }
  }
  if (art.mascot({ size: 64, mood: 'flat' }) !== artSandbox.verityMascot({ size: 64, mood: 'flat' })) {
    problems.push('the unsmiling mascot differs from the app\'s');
  }

  // The rule engine answers identically to the module the browser loads.
  const mine = new eng.Blocklist();
  const theirs = new real.blocklist.Blocklist();
  if (mine.size !== theirs.size) problems.push(`filter list size ${mine.size} != ${theirs.size}`);
  for (const host of HOSTS) {
    const a = mine.match(host);
    const b = theirs.match(host);
    if (JSON.stringify(a) !== JSON.stringify(b)) problems.push(`match(${host}): ${JSON.stringify(a)} != ${JSON.stringify(b)}`);
  }
  for (const url of URLS) {
    const a = eng.stripTrackingParams(url);
    const b = real.blocklist.stripTrackingParams(url);
    if (a !== b) problems.push(`stripTrackingParams(${url}): ${a} != ${b}`);
  }
  for (const input of INPUTS) {
    for (const engineKey of ['duckduckgo', 'startpage', 'google']) {
      const a = JSON.stringify(eng.resolveInput(input, engineKey));
      const b = JSON.stringify(real.search.resolveInput(input, engineKey));
      if (a !== b) problems.push(`resolveInput(${JSON.stringify(input)}, ${engineKey}): ${a} != ${b}`);
    }
  }

  // The strip's own rule must hold: a suffix match, never a substring one.
  const boundary = [['ad.doubleclick.net', true], ['doubleclick.net', true], ['notdoubleclick.net', false], ['doubleclick.net.evil.com', false]];
  for (const [host, expected] of boundary) {
    const actual = Boolean(mine.match(host));
    if (actual !== expected) problems.push(`boundary rule broken for ${host}: ${actual}`);
  }

  return { probes: HOSTS.length + URLS.length + INPUTS.length * 3 + 4, rules: mine.size };
}

/* --------------------------------------------------------------------- Run
 */
console.log('building the Verity site from the app\'s sources\n');
fs.mkdirSync(ASSETS, { recursive: true });

let checks = null;
try {
  art();
  write('assets/palette.css', palette());
  const real = engine();
  const copies = shots();
  checks = verify(real);
  const payload = data(real, checks);
  write('.nojekyll', '');
  note(`palette: ${read('src/renderer/chrome.css').match(/--accent:\s*#[0-9a-f]{6}/i)[0]} (dark), lifted from chrome.css`);
  if (electronStubbed) note('settings.js loaded with Electron stubbed out (build-time only)');
  note(`filter list: ${payload.filterList.total} rules in ${Object.keys(payload.filterList.byCategory).length} categories`);
  note(`search engines: ${payload.searchEngines.map((e) => e.label).join(', ')}`);
  note(`captures copied from artifacts/: ${copies}`);
} catch (error) {
  problems.push(`build failed: ${error.stack || error.message}`);
}

const changed = wrote.filter((entry) => entry.changed);
console.log('');
for (const entry of wrote) {
  const mark = entry.changed ? 'wrote' : ' same';
  console.log(`  ${mark}  docs/${entry.rel.padEnd(28)} ${String((entry.bytes / 1024).toFixed(1)).padStart(8)} KiB`);
}
console.log(`\n  ${changed.length} of ${wrote.length} generated files changed, ${wrote.length - changed.length} already current`);

if (problems.length) {
  console.error(`\n${problems.length} problem(s):`);
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}
console.log(`\n  verified: ${checks.probes} probe cases match the app's own modules (${checks.rules} rules)`);
console.log('  ok — docs/ is ready to publish\n');
